//! Driving the TPC-DS row generators, shared by the DAT and CSV outputs.
//!
//! Both outputs walk the generators identically — same row order, same seed
//! consumption — and differ only in how a chunk of rows is formatted into a
//! buffer. That difference is captured by [`RowFormat`]; everything else lives
//! here so the two formats cannot drift apart.
//!
//! Generation is parallel, using the same mechanism as the TPC-H text outputs:
//! each table is split into chunks of source rows
//! ([`TpcdsGenerationPlan`](super::plan::TpcdsGenerationPlan)), the chunks are
//! formatted into in memory buffers on separate threads, and a single writer
//! task appends the buffers to the output file in order (see
//! [`generate_file`]).

use super::runner::PlannedTable;
use crate::generate::{generate_file, Source};
use log::info;
use std::io;
use std::marker::PhantomData;
use std::ops::RangeInclusive;
use std::path::{Path, PathBuf};
use tpcdsgen::config::{Session, Table};
use tpcdsgen::row::*;

/// Return the output path for `table`'s file, following `tpchgen-cli`'s
/// `--parts`/`--part` naming convention:
///
/// When `--parts` was not requested creates a single `<table>.<ext>` file, otherwise
/// written into a subdirectory like `<table>/<table>.<chunk>.<ext>`.
///
/// Note that `--parts 1` is also written to a subdirectory.
///
/// This function creates the per-table subdirectory as needed.
pub(super) fn output_path(
    output_dir: &Path,
    table: Table,
    ext: &str,
    session: &Session,
) -> io::Result<PathBuf> {
    // sub directory `<table>/<table>.<chunk>.<ext>`
    if session.is_partitioned() {
        let dir = output_dir.join(table.get_name());
        std::fs::create_dir_all(&dir)?;
        Ok(dir.join(format!(
            "{}.{}.{ext}",
            table.get_name(),
            session.get_chunk_number()
        )))
    } else {
        // single `<table>.<ext>` file
        Ok(output_dir.join(format!("{}.{ext}", table.get_name())))
    }
}

/// A text output format for the TPC-DS row generators (DAT or CSV).
///
/// One instance formats every table, so implementations hold only the
/// format's options (such as the CSV delimiter), never per-table state.
pub(super) trait RowFormat: Clone + Send + 'static {
    /// The file extension of this format's output files.
    const EXTENSION: &'static str;

    /// Write the header line for `table` into `buffer`, if this format has
    /// one. Called exactly once per output file, before any rows.
    fn write_header(&self, table: Table, buffer: Vec<u8>) -> Vec<u8>;

    /// Format `rows` (all belonging to `table`) into `buffer`.
    fn write_rows<I>(&self, table: Table, rows: I, buffer: Vec<u8>) -> Vec<u8>
    where
        I: Iterator<Item = GeneratedRow>;
}

/// Trait for creating row generators.
pub(super) trait RowGeneratorFactory: RowGenerator + Sized {
    fn create() -> Self;
}

macro_rules! impl_factory {
    ($($gen:ty),*) => {
        $(
            impl RowGeneratorFactory for $gen {
                fn create() -> Self { Self::new() }
            }
        )*
    };
}

